let current = "zh";
export function detectLang(pref) {
    if (pref === "zh" || pref === "en")
        return pref;
    const langs = navigator.languages?.length ? navigator.languages : [navigator.language || "en"];
    return langs.some((l) => l.toLowerCase().startsWith("zh")) ? "zh" : "en";
}
export function setLang(l) {
    current = l;
    document.documentElement.lang = l === "zh" ? "zh-CN" : "en";
}
export function lang() {
    return current;
}
export function t(key, params = {}) {
    const dict = current === "zh" ? zh : en;
    return dict[key].replace(/\{(\w+)\}/g, (_, k) => String(params[k] ?? ""));
}
export function helpLines() {
    return current === "zh" ? zh.help : en.help;
}
export function fmtDay(ts) {
    return new Date(ts * 1000).toLocaleDateString(current === "zh" ? "zh-CN" : "en-US", { year: "numeric", month: "long", day: "numeric" });
}
